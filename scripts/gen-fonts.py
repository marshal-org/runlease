"""Mirror the site's web fonts so they are served by the site itself.

Reads the Google Fonts stylesheet for every family and weight the site uses,
keeps each subset whose unicode-range covers a character the site actually
prints, downloads those files to site/fonts/ and writes site/fonts.css.
"""
import glob, io, os, re, sys, urllib.request

SITE = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'site', '')
CSS_URL = ('https://fonts.googleapis.com/css2?family=Bricolage+Grotesque:opsz,wght@12..96,500..800'
           '&family=IBM+Plex+Mono:wght@400;500;600&family=IBM+Plex+Sans:wght@400;500;600&display=swap')
UA = 'Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0.0.0 Safari/537.36'

def get(url):
    return urllib.request.urlopen(urllib.request.Request(url, headers={'User-Agent': UA}), timeout=30).read()

# every character the site can print
used = set()
for p in glob.glob(SITE + '*.html') + glob.glob(SITE + '*.js'):
    used |= set(io.open(p, encoding='utf-8').read())
used = {ord(c) for c in used if ord(c) > 31}

def covers(rng):
    for part in rng.split(','):
        part = part.strip().upper().replace('U+', '')
        lo, _, hi = part.partition('-')
        hi = hi or lo
        # U+01?? is shorthand for U+0100-01FF
        lo, hi = int(lo.replace('?', '0'), 16), int(hi.replace('?', 'F'), 16)
        if any(lo <= c <= hi for c in used):
            return True
    return False

css = get(CSS_URL).decode()
blocks = re.findall(r'/\* ([a-z-]+) \*/\s*@font-face \{(.*?)\}', css, re.S)
if not blocks:
    sys.exit('no @font-face rules found: the font stylesheet has changed shape, nothing written')
os.makedirs(SITE + 'fonts', exist_ok=True)
out, seen, total = [], {}, 0
for subset, body in blocks:
    fam = re.search(r"font-family: '([^']+)'", body).group(1)
    weight = re.search(r'font-weight: ([^;]+);', body).group(1).strip()
    url = re.search(r'url\((https://[^)]+\.woff2)\)', body).group(1)
    rng = re.search(r'unicode-range: ([^;]+);', body).group(1)
    if not covers(rng):
        continue
    if url not in seen:
        slug = fam.lower().replace(' ', '-')
        name = '%s-%s-%s.woff2' % (slug, weight.replace(' ', '-'), subset)
        if fam.startswith('Bricolage') or fam == 'IBM Plex Sans':
            name = '%s-%s.woff2' % (slug, subset)       # one variable file covers every weight
        # Two different files must never land on one name: that would set
        # several weights in whichever was written last.
        if name in seen.values():
            sys.exit('%s would be written twice from different sources: %s is not one variable file' % (name, fam))
        data = get(url)
        io.open(SITE + 'fonts/' + name, 'wb').write(data)
        seen[url] = name
        total += len(data)
    extra = ''.join('  %s;\n' % l.strip().rstrip(';') for l in body.strip().split('\n')
                    if l.strip().startswith(('font-stretch', 'font-variation-settings')))
    out.append("@font-face {\n  font-family: '%s';\n  font-style: normal;\n  font-weight: %s;\n%s  font-display: swap;\n"
               "  src: url(fonts/%s) format('woff2');\n  unicode-range: %s;\n}\n" % (fam, weight, extra, seen[url], rng))

head = ("/* The site's typefaces, served by the site itself: no request leaves for a font host.\n"
        "   Bricolage Grotesque, IBM Plex Sans and IBM Plex Mono are under the SIL Open Font\n"
        "   License 1.1 (fonts/OFL.txt). Generated by scripts/gen-fonts.py; only the subsets\n"
        "   that cover a character the site prints are kept. */\n")
io.open(SITE + 'fonts.css', 'w', encoding='utf-8').write(head + ''.join(out))
print('%d @font-face rules, %d files, %d KB' % (len(out), len(seen), total // 1024))
for n in sorted(set(seen.values())):
    print('  ', n, os.path.getsize(SITE + 'fonts/' + n) // 1024, 'KB')
