var manifestNewOutput string

func init() {
	manifestNewCmd.Flags().StringVarP(&manifestNewOutput, "output", "o", "", "output file path (default: <instance-name>-manifest.yaml)")
	manifestCmd.AddCommand(manifestNewCmd)
	manifestCmd.AddCommand(manifestSchemaCmd)
	rootCmd.AddCommand(manifestCmd)
}

var manifestCmd = &cobra.Command{
	Use:   "manifest",
	Short: "Manage runlease manifests",
}

// manifestSchemaCmd prints the full annotated manifest schema to stdout so
// users have a reference even when they installed runlease via a package
// manager and don't have the source checkout. The body is a single embedded
// const so it ships inside the binary.
var manifestSchemaCmd = &cobra.Command{
	Use:   "schema",
	Short: "Print the full annotated manifest schema",
	Long: `Print every supported manifest field with inline comments.

Pipe to a file to use as a starting point:

  runlease manifest schema > my-runner-manifest.yaml`,
	Run: func(cmd *cobra.Command, _ []string) {
		fmt.Fprint(cmd.OutOrStdout(), manifestSchemaYAML)
	},
}

// manifestSchemaYAML is the full annotated schema printed by `runlease
// manifest schema`. Keep this in sync with `pkg/manifest/manifest.go`.
const manifestSchemaYAML = `# Runlease manifest — full schema reference.
# Generated by "runlease manifest schema". Required fields are uncommented;
# optional fields are commented with their defaults.

# ── Required ────────────────────────────────────────────────────────────────

name: my-runner                # Instance name. Used as the registry key, the
                               # rl-<name>-<rand> hostname prefix, and the
                               # runlease-managed tag.
provider: gcp                  # "aws" or "gcp".
region: us-central1-a          # AWS region or GCP zone.

# One of (mutually exclusive):
instanceClass: compute.small   # Portable class: micro | small | medium | large | gpu
# instanceType: t3.large       # Concrete cloud type; takes precedence over class.

# ── Image ───────────────────────────────────────────────────────────────────
# Default: auto-detect. AWS resolves to the latest Amazon Linux 2023 AMI;
# GCP defaults to the debian-12 family.
# baseImage: ami-0abcdef1234567890
# baseImage: projects/debian-cloud/global/images/family/debian-12

# ── Disk ────────────────────────────────────────────────────────────────────
# diskSizeGb: 50               # Boot disk size in GB. Default: the image's own
                               # size (GCP debian-12 ~10GB; AWS AL2023 ~30GB).
                               # Must be >= the image minimum (can't shrink).

# ── Networking ──────────────────────────────────────────────────────────────
# publicIp: true               # Default: true if no relay, false if relay set.
                               # On GCP, false requires Cloud NAT for egress.
relay:
  addr: wss://relay.runlease.online   # Set for tunneled access (no inbound firewall).
                                   # Leave empty to use direct SSH on the public IP.

# ── Lifecycle ───────────────────────────────────────────────────────────────
reclaim:
  ttl: 2h                      # Auto-terminate after this duration (e.g. 90m, 2h, 1d).
  selfTermination: true        # Schedule the systemd-run timer that fires
                               # /usr/local/bin/runlease-terminate at TTL.
                               # The terminate script itself is ALWAYS installed
                               # (manual escape: "sudo runlease-terminate").

# tags:                        # AWS tags / GCP labels. User keys override the
#   env: dev                   # auto-injected runlease-* keys.
#   team: platform

# ── Sudo ───────────────────────────────────────────────────────────────────
# sudo: passwordless           # NOPASSWD: ALL for runlease-agent.
                               # Default "locked" — only runlease-terminate is sudo-allowed.

# ── Setup scripts ──────────────────────────────────────────────────────────
# Run as root after the runlease bootstrap completes. Output streams to
# /var/log/runlease-setup.log; /run/runlease-setup-done is touched on success
# (and the __RUNLEASE_SETUP_DONE__ marker is emitted to the log) so
# "runlease up --attach" can detect completion.
# setup:
#   - name: install-k3s
#     run: |
#       curl -sfL https://get.k3s.io | INSTALL_K3S_EXEC="--write-kubeconfig-mode=644" sh -
#       until k3s kubectl get nodes 2>/dev/null | grep -q ' Ready'; do sleep 1; done
#   - name: seed
#     file: ./scripts/seed.sh  # Local file inlined at manifest-load time.

# ── Port forwards ──────────────────────────────────────────────────────────
# Auto-applied by "runlease up --attach" and "runlease forward --all <name>".
# Persisted to the registry so the manifest isn't re-read at use time.
# forwards:
#   - name: kube-api
#     local: 16443             # Local port to listen on (default bind 127.0.0.1).
#     remote: 6443             # Remote port to dial on the instance.
#     # direction: local       # default; "remote" for ssh -R semantics.
#     # bind: 0.0.0.0          # default 127.0.0.1.
#     # host: localhost        # default; remote-side hostname.

# ── AWS-specific ───────────────────────────────────────────────────────────
# aws:
#   securityGroupIDs:
#     - sg-xxxxx
#   subnetID: subnet-xxxxx
#   instanceProfile: arn:aws:iam::123456789012:instance-profile/my-profile

# ── GCP-specific ───────────────────────────────────────────────────────────
# gcp:
#   serviceAccount: deployer@my-project.iam.gserviceaccount.com
#     # for selfTermination, this SA needs the compute.instances.delete IAM
#     # permission (scope alone is not enough) - see docs/manifest.md
#   networkTags:
#     - allow-egress-only
`

// manifestNewCmd is the canonical name; "init" is kept as an alias so old
// scripts/docs that still say "runlease manifest init" keep working.
var manifestNewCmd = &cobra.Command{
	Use:     "new",
	Aliases: []string{"init"},
	Short:   "Interactively generate a new manifest YAML",
	Long: `Interactively generate a new manifest YAML.

Defaults to writing <instance-name>-manifest.yaml in the current directory.
Pass -o/--output to override.`,
	RunE: runManifestNew,
}

const manifestTemplate = `name: {{ .Name }}
provider: {{ .Provider }}
region: {{ .Region }}
instanceClass: {{ .InstanceClass }}
{{- if .BaseImage }}
baseImage: {{ .BaseImage }}
{{- else }}
# baseImage: (auto-detected at launch)
{{- end }}
# diskSizeGb: 50               # boot disk size in GB (default: image's size)
reclaim:
  ttl: {{ .TTL }}
{{- if .RelayAddr }}
relay:
  addr: {{ .RelayAddr }}
{{- end }}
{{- if eq .Sudo "passwordless" }}
sudo: passwordless              # NOPASSWD: ALL for runlease-agent
{{- end }}
# Optional fields (uncomment to use):
# publicIp: true
# tags:
#   env: dev
#   team: platform
#
# sudo: passwordless           # NOPASSWD: ALL for runlease-agent (default: locked)
#
# setup:                       # scripts run as root after bootstrap; output
#   - name: install            # streams to /var/log/runlease-setup.log; touched
#     run: |                   # /run/runlease-setup-done on success
#       curl -sfL https://get.k3s.io | sh -
#   # - name: seed
#   #   file: ./scripts/seed.sh  # local file inlined at launch time
#
# forwards:                    # auto-applied by 'runlease up --attach' and
#   - name: app                # 'runlease forward --all <name>'
#     local: 8080              # direction: local (default) or remote
#     remote: 80               # host: localhost (default)
{{- if eq .Provider "aws" }}
#
# aws:
#   securityGroupIDs:
#     - sg-xxxxx
#   subnetID: subnet-xxxxx
#   instanceProfile: arn:aws:iam::123456789012:instance-profile/my-profile
{{- end }}
{{- if eq .Provider "gcp" }}
#
# gcp:
#   serviceAccount: my-sa@my-project.iam.gserviceaccount.com
#   networkTags:
#     - allow-ssh
{{- end }}
`

type manifestTemplateData struct {
	Name          string
	Provider      string
	Region        string
	InstanceClass string
	BaseImage     string
	TTL           string
	RelayAddr     string
	Sudo          string // "locked" or "passwordless"; only renders into YAML when passwordless
}

func runManifestNew(cmd *cobra.Command, _ []string) error {
	out := cmd.OutOrStdout()

	// Exit cleanly on Ctrl+C — Go retries interrupted I/O, so the signal
	// would otherwise be swallowed by the blocking scanner.Scan() call.
	// (Same pattern as `runlease configure`.)
	sigCh := make(chan os.Signal, 1)
	signal.Notify(sigCh, syscall.SIGINT, syscall.SIGTERM)
	go func() {
		<-sigCh
		fmt.Fprintln(out, "\nCancelled.")
		os.Exit(0)
	}()
	defer signal.Stop(sigCh)

	scanner := bufio.NewScanner(cmd.InOrStdin())

	ask := func(question, def string) string {
		if def != "" {
			fmt.Fprintf(out, "  %s [%s]: ", question, def)
		} else {
			fmt.Fprintf(out, "  %s: ", question)
		}
		if !scanner.Scan() {
			return def
		}
		val := strings.TrimSpace(scanner.Text())
		if val == "" {
			return def
		}
		return val
	}

	cfg, _ := rlconfig.Load(defaultConfigPath())
	if cfg == nil {
		cfg = &rlconfig.Config{}
	}

	fmt.Fprintf(out, "Creating a new runlease manifest. Press Enter to accept defaults.\n\n")

	name := ask("Instance name", "my-runner")

	fmt.Fprintf(out, "\n  Providers: aws, gcp\n")
	provDefault := cfg.Defaults.Provider
	if provDefault == "" {
		provDefault = "gcp"
	}
	prov := ask("Provider", provDefault)

	regionDefault := cfg.Defaults.Region
	if regionDefault == "" {
		regionDefault = map[string]string{"gcp": "us-central1-a", "aws": "us-east-1"}[prov]
	}
	region := ask("Region / zone", regionDefault)

	fmt.Fprintf(out, "\n  Classes: compute.micro, compute.small, compute.medium, compute.large, compute.gpu\n")
	sizeDefault := cfg.Defaults.Size
	if sizeDefault == "" {
		sizeDefault = "compute.small"
	}
	class := ask("Instance class", sizeDefault)

	imageDefault := map[string]string{
		"gcp": "projects/debian-cloud/global/images/family/debian-12",
		"aws": "",
	}[prov]
	var imagePrompt string
	if prov == "aws" {
		fmt.Fprintf(out, "\n  AWS: leave blank to auto-detect the latest Amazon Linux 2023 AMI at launch time.\n")
		imagePrompt = "Base image (AMI ID, or Enter to auto-detect)"
	} else {
		imagePrompt = "Base image"
	}
	image := ask(imagePrompt, imageDefault)

	fmt.Fprintln(out)
	relayAddr := ask("Relay address (leave empty to skip)", cfg.Relay.Addr)

	ttlDefault := cfg.Defaults.TTL
	if ttlDefault == "" {
		ttlDefault = "2h"
	}
	ttl := ask("TTL", ttlDefault)

	// Sudo posture for runlease-agent. Locked-by-default keeps the security
	// model intact (only the terminate script is sudo-allowed). Passwordless
	// is the opt-in for users who want their setup scripts to install
	// packages or who plan to sudo manually inside the VM.
	fmt.Fprintf(out, "\n  Options: locked | passwordless\n")
	fmt.Fprintf(out, "    locked       — no sudo for runlease-agent (default)\n")
	fmt.Fprintf(out, "    passwordless — NOPASSWD: ALL (needed to install software, run docker, etc.)\n")
	sudo := strings.ToLower(ask("Sudo", "locked"))
	switch sudo {
	case "locked", "passwordless":
	default:
		return fmt.Errorf("invalid sudo value %q (expected locked or passwordless)", sudo)
	}

	data := manifestTemplateData{
		Name:          name,
		Provider:      prov,
		Region:        region,
		InstanceClass: class,
		BaseImage:     image,
		TTL:           ttl,
		RelayAddr:     relayAddr,
		Sudo:          sudo,
	}

	tmpl, err := template.New("manifest").Parse(manifestTemplate)
	if err != nil {
		return err
	}

	// Resolve the output filename: explicit --output wins; otherwise derive
	// from the entered instance name so multiple manifests can sit side-by-side
	// in one project directory without colliding on `manifest.yaml`.
	outputPath := manifestNewOutput
	if outputPath == "" {
		outputPath = name + "-manifest.yaml"
	}

	f, err := os.Create(outputPath)
	if err != nil {
		return fmt.Errorf("creating %s: %w", outputPath, err)
	}
	defer f.Close()

	if err := tmpl.Execute(f, data); err != nil {
		return fmt.Errorf("writing manifest: %w", err)
	}

	fmt.Fprintf(out, "\n✓ Written to %s\n", outputPath)
	fmt.Fprintf(out, "  Launch with:           runlease up -m %s\n", outputPath)
	fmt.Fprintf(out, "  See every field with:  runlease manifest schema\n\n")
	return nil
}
