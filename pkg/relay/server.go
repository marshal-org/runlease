// ── helpers ───────────────────────────────────────────────────────────────────

func bridge(a, b net.Conn) {
	done := make(chan struct{}, 1)
	go func() { io.Copy(a, b); done <- struct{}{} }() //nolint:errcheck
	go func() { io.Copy(b, a); done <- struct{}{} }() //nolint:errcheck
	<-done
	a.Close()
	b.Close()
}

func readLine(conn net.Conn) (string, error) {
	var buf []byte
	b := [1]byte{}
	for {
		if _, err := conn.Read(b[:]); err != nil {
			return "", err
		}
		if b[0] == '\n' {
			break
		}
		buf = append(buf, b[0])
		if len(buf) > 4096 {
			return "", fmt.Errorf("line too large")
		}
	}
	return strings.TrimRight(string(buf), "\r"), nil
}

func readMsg(conn net.Conn) (wireMsg, error) {
	line, err := readLine(conn)
	if err != nil {
		return wireMsg{}, err
	}
	var m wireMsg
	return m, json.Unmarshal([]byte(line), &m)
}

func writeMsg(conn net.Conn, m wireMsg) error {
	data, err := json.Marshal(m)
	if err != nil {
		return err
	}
	_, err = conn.Write(append(data, '\n'))
	return err
}

func drainClose(ch chan net.Conn) {
	select {
	case c := <-ch:
		c.Close()
	default:
	}
}

// protocolOf reads the protocol a handshake names; "" is version 1.
func protocolOf(s string) (int, bool) {
	if s == "" {
		return 1, true
	}
	n, err := strconv.Atoi(s)
	return n, err == nil
}

