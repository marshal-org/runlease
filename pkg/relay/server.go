const (
	handshakeTimeout = 30 * time.Second
	tokenTTL         = 24 * time.Hour

	// Slot tokens are bearer secrets chosen by the CLI. The relay refuses
	// anything too short to be unguessable, and anything that is not plain
	// token characters, before it touches the slot table or the logs.
	minTokenLen = 32
	maxTokenLen = 128
)

// validToken reports whether tok is an acceptable slot token: 32 to 128
// characters from [A-Za-z0-9_-]. The CLI sends 64 hex characters.
func validToken(tok string) bool {
	if len(tok) < minTokenLen || len(tok) > maxTokenLen {
		return false
	}
	for i := 0; i < len(tok); i++ {
		c := tok[i]
		switch {
		case c >= 'a' && c <= 'z', c >= 'A' && c <= 'Z', c >= '0' && c <= '9', c == '-', c == '_':
		default:
			return false
		}
	}
	return true
}

// shortTok returns a log-safe prefix of a token. It never panics, whatever
// the length of its input.
func shortTok(tok string) string {
	if len(tok) > 8 {
		return tok[:8] + "…"
	}
	return "…"
}

// Server is a WebSocket relay server that implements http.Handler.
//
// Security model
// ──────────────
// The relay is credential-less: it never sees SSH keys or cloud credentials.
// It matches connections using a per-instance random token generated by the CLI.
// Even if the relay is compromised:
//   - It cannot authenticate to the instance (no SSH client key)
//   - It cannot impersonate the instance (no SSH host key)
//   - It cannot decrypt session traffic (AES-GCM, keys derived via ECDH)
//   - Routing the wrong socket to the CLI fails the FixedHostKey check
//
// Token lifecycle
// ───────────────
//  1. CLI (runlease up)      → relay: register token  (pre-authorises the slot)
//  2. Instance (agent)       → relay: claim the slot with that token
//  3. CLI (runlease connect) → relay: join the slot
//
// Config holds relay server configuration.
type Config struct {
	AgentPath string // path to runlease-agent binary served at GET /agent; empty disables
	// AgentCacheDir keeps the agents of other releases, fetched from
	// AgentReleaseURL and served at GET /agent/sha256/<hex>. Empty serves only
	// the agent at AgentPath by digest.
	AgentCacheDir string
	// AgentReleaseURL is where an agent of another release is fetched from;
	// {version} is replaced by its tag. Empty turns fetching off.
	AgentReleaseURL string
	Auth            AuthConfig // Google OAuth allow-list; zero value disables auth
	// MaxSlots caps the number of live slots. Registration is refused once the
	// cap is reached, so one caller cannot exhaust the relay's memory. Zero
	// means no cap.
	MaxSlots int
	// Tiers sets the per-identity limits the relay starts with; ReloadTiers
	// and SetTiers replace them while it runs. Nil means one tier with no
	// per-identity limits.
	Tiers *Tiers
	// GoogleClientSecret is published, with the first of Auth.GoogleClientIDs,
	// in the discovery document so `runlease login` can sign a user in. For an
	// installed-application OAuth client this value is not confidential.
	GoogleClientSecret string
	// Version is reported in the discovery document.
	Version string
}

type Server struct {
	log      *slog.Logger
	cfg      Config
	agents   *agentStore // nil when the relay serves no agent
	upgrader websocket.Upgrader
	mu       sync.Mutex
	slots    map[string]*slot // keyed by token
	owned    map[string]int   // live slots per owner email

	// live holds the limits in force. It starts as cfg.Tiers and is replaced
	// by SetTiers and ReloadTiers; read it through tiers(), never cfg.Tiers.
	live     atomic.Pointer[Tiers]
	reloadMu sync.Mutex
	tiersSum []byte // SHA-256 of the tiers file as last read
}

type slot struct {
	owner           string        // email of the identity that registered it; "" when auth is off
	tier            string        // tier name at registration
	idleTTL         time.Duration // release when the agent has been absent this long; 0 = never
	cancel          context.CancelFunc
	expiresAt       time.Time
	registeredAt    time.Time // for the "lived" figure logged at release
	instanceClaimed atomic.Bool
	instanceReady   atomic.Bool // set true once the yamux session is established
	instanceCh      chan net.Conn
	clientCh        chan net.Conn // clients queue here for the coordinator to pick up
	done            chan struct{} // closed when the coordinator goroutine exits
}

func New(log *slog.Logger, cfg Config) *Server {
	s := &Server{
		log:      log,
		cfg:      cfg,
		upgrader: websocket.Upgrader{CheckOrigin: func(r *http.Request) bool { return true }},
		slots:    make(map[string]*slot),
		owned:    make(map[string]int),
	}
	s.live.Store(cfg.Tiers)
	if cfg.AgentPath != "" || cfg.AgentCacheDir != "" {
		st, err := newAgentStore(cfg.AgentCacheDir, cfg.AgentReleaseURL, cfg.AgentPath)
		if err != nil {
			log.Error("agents by digest are off", "err", err)
		} else {
			s.agents = st
		}
	}
	return s
}

// ── HTTP routing ──────────────────────────────────────────────────────────────

func (s *Server) ServeHTTP(w http.ResponseWriter, r *http.Request) {
	switch r.URL.Path {
	case "/relay":
		s.handleUpgrade(w, r)
	case "/ready":
		s.handleReady(w, r)
	case "/agent":
		s.serveAgent(w, r)
	case "/me":
		s.handleMe(w, r)
	case "/.well-known/runlease-relay":
		s.handleDiscovery(w, r)
	case "/health":
		w.WriteHeader(http.StatusOK)
	default:
		if strings.HasPrefix(r.URL.Path, "/agent/sha256/") {
			s.serveAgentByDigest(w, r)
			return
		}
		http.NotFound(w, r)
	}
}

// handleReady reports whether the instance for a given token has registered and
// is ready to accept a client. The token is passed in the X-Relay-Token header
// to keep it out of access logs. Returns 200 (ready), 202 (registered but
// instance not yet ready), 404 (token unknown or expired).
func (s *Server) handleReady(w http.ResponseWriter, r *http.Request) {
	token := r.Header.Get("X-Relay-Token")
	if token == "" {
		http.Error(w, "missing X-Relay-Token header", http.StatusBadRequest)
		return
	}
	s.mu.Lock()
	sl, ok := s.slots[token]
	s.mu.Unlock()
	if !ok || time.Now().After(sl.expiresAt) {
		http.NotFound(w, r)
		return
	}
	if sl.instanceReady.Load() {
		w.WriteHeader(http.StatusOK)
	} else {
		w.WriteHeader(http.StatusAccepted) // 202: slot exists, instance not ready yet
	}
}

func (s *Server) handleUpgrade(w http.ResponseWriter, r *http.Request) {
	// Extract the bearer token from the HTTP request before upgrading — it's
	// not accessible after the WebSocket handshake completes.
	bearer := strings.TrimPrefix(r.Header.Get("Authorization"), "Bearer ")

	client := clientLabel(r.UserAgent())

	ws, err := s.upgrader.Upgrade(w, r, nil)
	if err != nil {
		s.log.Warn("websocket upgrade failed", "err", err)
		return
	}
	go s.dispatch(newWSConn(ws), bearer, client)
}

func newWSConn(ws *websocket.Conn) net.Conn {
	return &wsConn{conn: ws}
}

// ── protocol dispatch ─────────────────────────────────────────────────────────
//
// All messages are binary WebSocket frames containing newline-terminated JSON.
// After handshake the agent's connection is owned by yamux; client connections
// remain raw byte streams (yamux is terminated by the relay on the agent side).
//
// Register (CLI during runlease up):
//   → {"role":"register","token":"<tok>"}
//   ← {"status":"ok"}
//
// Release (CLI during runlease down):
//   → {"role":"release","token":"<tok>"}
//   ← {"status":"ok"}
//
// Instance (runlease-agent on boot):
//   → {"role":"instance","token":"<tok>"}
//   ← {"status":"registered"}
//   <yamux server-side from agent; relay opens streams for each client>
//
// Client (runlease connect, exec, forward, push, pull — any number, concurrent):
//   → {"role":"client","token":"<tok>"}
//   ← {"status":"connected"}
//   raw SSH bytes (relay bridges to a fresh yamux stream against the agent)

// The wire protocol between CLI, relay and agent. A sender puts Protocol in
// its handshake; a relay accepts MinProtocol to MaxProtocol. A handshake with
// no protocol is version 1 (every release before the field existed). Raise
// MaxProtocol for an additive change; raise MinProtocol only to drop old
// clients on purpose. The value is a string so a reply stays readable by old
// agents, which decode the handshake as map[string]string.
const (
	Protocol    = 1
	MinProtocol = 1
	MaxProtocol = 1
)

type wireMsg struct {
	Role    string `json:"role,omitempty"`
	Token   string `json:"token,omitempty"`
	Proto   string `json:"proto,omitempty"`
	Status  string `json:"status,omitempty"`
	Message string `json:"message,omitempty"`
}

// clientLabel reduces a User-Agent header to something safe to put in a log
// line: the CLI's own "runlease/<version> (<os>/<arch>)", cut to a sane length
// and to plain characters. Anything else is recorded as "other", so a browser
// or a scanner cannot write arbitrary text into the usage records.
func clientLabel(ua string) string {
	if !strings.HasPrefix(ua, "runlease/") {
		return "other"
	}
	if len(ua) > 64 {
		ua = ua[:64]
	}
	for _, c := range ua {
		ok := c >= 'a' && c <= 'z' || c >= 'A' && c <= 'Z' || c >= '0' && c <= '9' || strings.ContainsRune("/.-+_ ()", c)
		if !ok {
			return "other"
		}
	}
	return ua
}

func (s *Server) dispatch(conn net.Conn, bearer, client string) {
	conn.SetDeadline(time.Now().Add(handshakeTimeout)) //nolint:errcheck
	hs, err := readMsg(conn)
	conn.SetDeadline(time.Time{}) //nolint:errcheck

	if err != nil {
		writeMsg(conn, wireMsg{Status: "error", Message: "invalid handshake"}) //nolint:errcheck
		conn.Close()
		return
	}
	if p, ok := protocolOf(hs.Proto); !ok || p < MinProtocol || p > MaxProtocol {
		writeMsg(conn, wireMsg{Status: "error", Message: fmt.Sprintf( //nolint:errcheck
			"this relay speaks protocol %d to %d and the other side speaks %q. Upgrade runlease (a machine gets its agent from the CLI that launched it)", MinProtocol, MaxProtocol, hs.Proto)})
		conn.Close()
		return
	}
	if !validToken(hs.Token) {
		writeMsg(conn, wireMsg{Status: "error", Message: "invalid token: want 32 to 128 characters of [A-Za-z0-9_-]"}) //nolint:errcheck
		conn.Close()
		return
	}

	switch hs.Role {
	case "register":
		s.handleRegister(conn, hs.Token, bearer, client)
	case "release":
		s.handleRelease(conn, hs.Token)
	case "instance":
		s.handleInstance(conn, hs.Token)
	case "client":
		s.handleClient(conn, hs.Token)
	default:
		writeMsg(conn, wireMsg{Status: "error", Message: "unknown role"}) //nolint:errcheck
		conn.Close()
	}
}

func (s *Server) handleRegister(conn net.Conn, token, bearer, client string) {
	defer conn.Close()

	id, err := s.cfg.Auth.identify(context.Background(), bearer)
	if err != nil {
		s.log.Warn("register rejected", "err", err)
		writeMsg(conn, wireMsg{Status: "unauthorized", Message: err.Error()}) //nolint:errcheck
		return
	}
	tierName, tier := s.tiers().For(id.Email)

	s.mu.Lock()
	if _, exists := s.slots[token]; exists {
		s.mu.Unlock()
		writeMsg(conn, wireMsg{Status: "error", Message: "token already registered"}) //nolint:errcheck
		return
	}
	if s.cfg.MaxSlots > 0 && len(s.slots) >= s.cfg.MaxSlots {
		s.mu.Unlock()
		s.log.Warn("register rejected: relay at slot capacity", "max_slots", s.cfg.MaxSlots)
		writeMsg(conn, wireMsg{Status: "error", Message: "relay is at capacity, try again later"}) //nolint:errcheck
		return
	}
	// The per-identity cap only applies to a known identity. With auth off
	// there is nobody to count against, and only the global cap holds.
	if id.Email != "" && tier.MaxSlots > 0 && s.owned[id.Email] >= tier.MaxSlots {
		s.mu.Unlock()
		s.log.Info("register rejected: identity at tier limit", "owner", id.Email, "tier", tierName, "max_slots", tier.MaxSlots, "client", client)
		writeMsg(conn, wireMsg{Status: "limit", Message: fmt.Sprintf( //nolint:errcheck
			"the %q tier allows %d machines at once and you have %d. Run 'runlease down' on one you no longer need, or wait for it to expire",
			tierName, tier.MaxSlots, tier.MaxSlots)})
		return
	}
	ctx, cancel := context.WithDeadline(context.Background(), time.Now().Add(tier.slotTTL()))
	sl := &slot{
		owner:        id.Email,
		tier:         tierName,
		idleTTL:      time.Duration(tier.IdleTTL),
		cancel:       cancel,
		expiresAt:    time.Now().Add(tier.slotTTL()),
		registeredAt: time.Now(),
		instanceCh:   make(chan net.Conn, 1),
		clientCh:     make(chan net.Conn, 1),
		done:         make(chan struct{}),
	}
	s.slots[token] = sl
	if sl.owner != "" {
		s.owned[sl.owner]++
	}
	s.mu.Unlock()

	s.startCoordinator(ctx, token, sl)
	writeMsg(conn, wireMsg{Status: "ok"}) //nolint:errcheck
	// One of the usage records (see deploy/relay/gcp/usage). It carries who,
	// which tier and which CLI build, and nothing about what the machine does.
	s.log.Info("token registered", "token", shortTok(token), "owner", sl.owner, "tier", tierName, "client", client)
}

// handleRelease frees a slot before it expires, so its owner gets the place
// back in their tier at once. Holding the token is the authority: it is the
// same secret that already lets its holder use the slot. Releasing an unknown
// token succeeds, so the call is safe to repeat.
func (s *Server) handleRelease(conn net.Conn, token string) {
	defer conn.Close()
	s.mu.Lock()
	sl, ok := s.slots[token]
	s.mu.Unlock()
	if ok {
		sl.cancel()
		<-sl.done
		s.log.Info("slot released", "token", shortTok(token), "owner", sl.owner, "tier", sl.tier, "lived_s", int(time.Since(sl.registeredAt).Seconds()))
	}
	writeMsg(conn, wireMsg{Status: "ok"}) //nolint:errcheck
}

func (s *Server) handleInstance(conn net.Conn, token string) {
	s.mu.Lock()
	sl, ok := s.slots[token]
	s.mu.Unlock()

	if !ok || time.Now().After(sl.expiresAt) {
		writeMsg(conn, wireMsg{Status: "unauthorized", Message: "token not registered or expired"}) //nolint:errcheck
		conn.Close()
		return
	}
	if !sl.instanceClaimed.CompareAndSwap(false, true) {
		writeMsg(conn, wireMsg{Status: "busy", Message: "instance slot already claimed"}) //nolint:errcheck
		conn.Close()
		return
	}
	sl.instanceCh <- conn
}

func (s *Server) handleClient(conn net.Conn, token string) {
	s.mu.Lock()
	sl, ok := s.slots[token]
	s.mu.Unlock()

	if !ok || time.Now().After(sl.expiresAt) {
		writeMsg(conn, wireMsg{Status: "unauthorized", Message: "token not registered or expired"}) //nolint:errcheck
		conn.Close()
		return
	}
	// Concurrency is expected: the coordinator runs an OpenStream per client.
	// Block (with the handshake deadline still in effect) until the coordinator
	// picks it up, or bail out if the coordinator has exited (slot expired /
	// removed) — a bare send on clientCh with no reader would otherwise leak
	// this goroutine and its conn forever.
	select {
	case sl.clientCh <- conn:
	case <-sl.done:
		writeMsg(conn, wireMsg{Status: "error", Message: "slot closed"}) //nolint:errcheck
		conn.Close()
	}
}

func (s *Server) startCoordinator(ctx context.Context, token string, sl *slot) {
	go func() {
		// The slot leaves the table first, so anyone woken by close(done) sees
		// it gone and the owner's count already lowered. close(done) then
		// unblocks clients waiting in handleClient, and the drain mops up a
		// conn that raced into the buffer on the way out.
		defer func() {
			sl.cancel()
			s.removeSlot(token)
			close(sl.done)
			drainClose(sl.instanceCh)
			drainClose(sl.clientCh)
		}()

		for {
			// Wait for the agent to (re)connect. A tier may bound that wait:
			// an agent that stays away means the machine is gone, and the
			// owner should get the slot back.
			var idle <-chan time.Time
			var timer *time.Timer
			if sl.idleTTL > 0 {
				timer = time.NewTimer(sl.idleTTL)
				idle = timer.C
			}
			var instanceConn net.Conn
			select {
			case instanceConn = <-sl.instanceCh:
				if timer != nil {
					timer.Stop()
				}
			case <-idle:
				s.log.Info("slot released: agent absent", "token", shortTok(token), "owner", sl.owner, "tier", sl.tier, "lived_s", int(time.Since(sl.registeredAt).Seconds()), "idle_ttl", sl.idleTTL.String())
				return
			case <-ctx.Done():
				if timer != nil {
					timer.Stop()
				}
				return
			}

			if err := writeMsg(instanceConn, wireMsg{Status: "registered"}); err != nil {
				instanceConn.Close()
				sl.instanceClaimed.Store(false)
				continue
			}
			s.log.Info("instance registered", "token", shortTok(token))

			s.runMuxSession(ctx, token, sl, instanceConn)
			sl.instanceReady.Store(false)
			sl.instanceClaimed.Store(false)
			if ctx.Err() != nil {
				return
			}
		}
	}()
}

// runMuxSession wraps the agent's WebSocket as a yamux client session and
// opens one yamux stream per incoming CLI client. Returns when the agent
// disconnects (yamux session breaks) or the slot deadline expires.
func (s *Server) runMuxSession(ctx context.Context, token string, sl *slot, instanceConn net.Conn) {
	session, err := yamux.Client(instanceConn, yamuxConfig())
	if err != nil {
		s.log.Warn("yamux.Client init failed", "token", shortTok(token), "err", err)
		instanceConn.Close()
		return
	}
	defer session.Close()

	// As soon as the mux session is up, clients may connect — they no longer
	// need a per-session "ready" ack from the agent.
	sl.instanceReady.Store(true)
	s.log.Info("mux session active", "token", shortTok(token))

	for {
		select {
		case <-ctx.Done():
			drainClose(sl.clientCh)
			return
		case <-session.CloseChan():
			s.log.Info("mux session ended, awaiting agent reconnect", "token", shortTok(token))
			drainClose(sl.clientCh)
			return
		case clientConn := <-sl.clientCh:
			go s.handleMuxClient(session, clientConn, token)
		}
	}
}

func (s *Server) handleMuxClient(session *yamux.Session, clientConn net.Conn, token string) {
	stream, err := session.OpenStream()
	if err != nil {
		s.log.Warn("yamux OpenStream failed", "token", shortTok(token), "err", err)
		writeMsg(clientConn, wireMsg{Status: "error", Message: "mux open failed"}) //nolint:errcheck
		clientConn.Close()
		return
	}
	if err := writeMsg(clientConn, wireMsg{Status: "connected"}); err != nil {
		stream.Close()
		clientConn.Close()
		return
	}
	bridge(stream, clientConn)
}

// yamuxConfig returns the yamux config used by the relay (client side) when
// muxing CLI streams over the agent WebSocket. yamux keepalives stay enabled —
// the WebSocket layer doesn't ping on its own, so NAT timeouts can silently
// drop an idle outbound session.
func yamuxConfig() *yamux.Config {
	cfg := yamux.DefaultConfig()
	cfg.StreamOpenTimeout = 30 * time.Second
	cfg.LogOutput = io.Discard
	return cfg
}

func (s *Server) removeSlot(token string) {
	s.mu.Lock()
	if sl, ok := s.slots[token]; ok {
		delete(s.slots, token)
		if sl.owner != "" {
			if s.owned[sl.owner]--; s.owned[sl.owner] <= 0 {
				delete(s.owned, sl.owner)
			}
		}
	}
	s.mu.Unlock()
}

// ── account and discovery ─────────────────────────────────────────────────────

// handleMe reports the caller's identity, tier and usage. It takes the same
// bearer token as registration.
func (s *Server) handleMe(w http.ResponseWriter, r *http.Request) {
	if !s.cfg.Auth.enabled() {
		http.Error(w, "this relay runs without authentication", http.StatusNotFound)
		return
	}
	bearer := strings.TrimPrefix(r.Header.Get("Authorization"), "Bearer ")
	id, err := s.cfg.Auth.identify(r.Context(), bearer)
	if err != nil {
		http.Error(w, err.Error(), http.StatusUnauthorized)
		return
	}
	tierName, tier := s.tiers().For(id.Email)
	s.mu.Lock()
	used := s.owned[id.Email]
	s.mu.Unlock()
	writeJSON(w, map[string]any{
		"email":   id.Email,
		"tier":    tierName,
		"slots":   map[string]int{"used": used, "max": tier.MaxSlots},
		"slotTTL": tier.slotTTL().String(),
		"idleTTL": time.Duration(tier.IdleTTL).String(),
	})
}

// handleDiscovery tells a CLI how to sign in to this relay and what the
// default tier allows. Everything in it is public.
func (s *Server) handleDiscovery(w http.ResponseWriter, _ *http.Request) {
	auth := map[string]any{"required": s.cfg.Auth.enabled()}
	if len(s.cfg.Auth.GoogleClientIDs) > 0 {
		auth["google"] = map[string]string{
			"clientId":     s.cfg.Auth.GoogleClientIDs[0],
			"clientSecret": s.cfg.GoogleClientSecret,
		}
	}
	doc := map[string]any{"version": s.cfg.Version, "auth": auth, "protocol": map[string]int{"min": MinProtocol, "max": MaxProtocol}}
	if s.agents != nil {
		doc["agentByDigest"] = true
	}
	if name, tier := s.tiers().For(""); name != "" {
		doc["defaultTier"] = map[string]any{
			"name":     name,
			"maxSlots": tier.MaxSlots,
			"slotTTL":  tier.slotTTL().String(),
		}
	}
	writeJSON(w, doc)
}

func writeJSON(w http.ResponseWriter, v any) {
	w.Header().Set("Content-Type", "application/json")
	w.Header().Set("Cache-Control", "no-store")
	json.NewEncoder(w).Encode(v) //nolint:errcheck
}

