#!/usr/bin/env python3
"""Generate the Antigravity and Gemini CLI copies of the Claude Code plugin content.

The source of truth is plugin/ (the Claude Code plugin). Neither Google format can
point at it:

  - A Gemini CLI extension loads skills only from skills/ and commands only from
    commands/*.toml, both next to gemini-extension.json at the repository root.
  - An Antigravity plugin does not load commands/, so each command becomes a skill.

This script writes:

  skills/<name>/SKILL.md                         copy of plugin/skills/<name>/SKILL.md
  commands/runlease/<cmd>.toml                   from plugin/commands/<cmd>.md (Gemini CLI)
  antigravity/skills/runlease-<cmd>/SKILL.md     from plugin/commands/<cmd>.md (Antigravity)
  claude-directory/{skills,commands}/...         copies, plus LICENSE and the icon: the edition
                                                 submitted to the Claude plugin directory, which
                                                 takes no MCP server, mod or code file from an
                                                 organization it has not verified

Usage:
  scripts/gen-agent-plugins.py           write the files
  scripts/gen-agent-plugins.py --check   write nothing; exit 1 if anything is out of date,
                                         or if the manifests disagree on version or MCP server

Python 3.11+, standard library only.
"""

import json
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC_SKILLS = ROOT / "plugin" / "skills"
SRC_COMMANDS = ROOT / "plugin" / "commands"

OUT_SKILLS = ROOT / "skills"
OUT_GEMINI_COMMANDS = ROOT / "commands" / "runlease"
OUT_AGY_COMMAND_SKILLS = ROOT / "antigravity" / "skills"
OUT_DIRECTORY = ROOT / "claude-directory"
# Copied as they are into the directory edition. Its plugin.json and README.md are hand-written.
DIRECTORY_COPIES = ("skills", "commands", "LICENSE", ".claude-plugin/icon.png")

# What a command's argument placeholder becomes in each format.
CLAUDE_ARGS = "`$ARGUMENTS`"
GEMINI_ARGS = "`{{args}}`"
SKILL_ARGS = "whatever the person wrote after the command name, which may be nothing"

GENERATED = "Generated by scripts/gen-agent-plugins.py from plugin/commands/{name}.md. Do not edit."


def split_frontmatter(text, path):
    """Return (fields, body) for a Markdown file with simple `key: value` frontmatter."""
    if not text.startswith("---\n"):
        sys.exit(f"{path}: no frontmatter")
    head, sep, body = text[4:].partition("\n---\n")
    if not sep:
        sys.exit(f"{path}: frontmatter is not closed")
    fields = {}
    for line in head.splitlines():
        if not line.strip():
            continue
        key, colon, value = line.partition(":")
        if not colon:
            sys.exit(f"{path}: cannot read frontmatter line: {line}")
        value = value.strip()
        if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
            value = value[1:-1]
        fields[key.strip()] = value
    return fields, body.lstrip("\n")


def toml_basic(value):
    return json.dumps(value, ensure_ascii=False)


def gemini_command(name, fields, body):
    prompt = body.replace(CLAUDE_ARGS, GEMINI_ARGS).rstrip("\n")
    if "'''" in prompt:
        sys.exit(f"plugin/commands/{name}.md: contains ''' and cannot go in a TOML literal string")
    text = (
        f"# {GENERATED.format(name=name)}\n"
        f"description = {toml_basic(fields['description'])}\n"
        f"prompt = '''\n{prompt}\n'''\n"
    )
    tomllib.loads(text)  # fail here, not in the user's CLI
    return text


def antigravity_command_skill(name, fields, body):
    skill = f"runlease-{name}"
    description = fields["description"]
    hint = fields.get("argument-hint")
    if hint:
        description += f". Arguments: {hint}"
    text = body.replace(CLAUDE_ARGS, SKILL_ARGS).rstrip("\n")
    return skill, (
        "---\n"
        f"name: {skill}\n"
        f"description: {toml_basic(description)}\n"
        "disable-model-invocation: true\n"
        "---\n\n"
        f"<!-- {GENERATED.format(name=name)} -->\n\n"
        f"{text}\n"
    )


def wanted():
    """Map of output path -> content for every generated file."""
    out = {}
    for src in sorted(SRC_SKILLS.rglob("*")):
        if src.is_file():
            out[OUT_SKILLS / src.relative_to(SRC_SKILLS)] = src.read_bytes()
    for src in sorted(SRC_COMMANDS.glob("*.md")):
        fields, body = split_frontmatter(src.read_text(encoding="utf-8"), src)
        if "description" not in fields:
            sys.exit(f"{src}: no description")
        name = src.stem
        out[OUT_GEMINI_COMMANDS / f"{name}.toml"] = gemini_command(name, fields, body).encode()
        skill, text = antigravity_command_skill(name, fields, body)
        out[OUT_AGY_COMMAND_SKILLS / skill / "SKILL.md"] = text.encode()
    plugin = ROOT / "plugin"
    for item in DIRECTORY_COPIES:
        src = plugin / item
        files = [src] if src.is_file() else sorted(f for f in src.rglob("*") if f.is_file())
        for f in files:
            out[OUT_DIRECTORY / f.relative_to(plugin)] = f.read_bytes()
    return out


def existing():
    found = set()
    bases = [OUT_SKILLS, OUT_GEMINI_COMMANDS, OUT_AGY_COMMAND_SKILLS]
    bases += [OUT_DIRECTORY / "skills", OUT_DIRECTORY / "commands"]
    for base in bases:
        if base.is_dir():
            found.update(p for p in base.rglob("*") if p.is_file())
    return found


def manifest_problems():
    """The hand-written manifests must agree with the Claude Code plugin."""
    problems = []

    def load(rel):
        return json.loads((ROOT / rel).read_text(encoding="utf-8"))

    claude = load("plugin/.claude-plugin/plugin.json")
    antigravity = load(".antigravity-plugin/plugin.json")
    gemini = load("gemini-extension.json")
    directory = load("claude-directory/.claude-plugin/plugin.json")
    for key in ("mcpServers", "hooks", "types", "userConfig"):
        if key in directory:
            problems.append(f"claude-directory/.claude-plugin/plugin.json: {key} is not allowed in the directory edition")
    for label, manifest in (
        (".antigravity-plugin/plugin.json", antigravity),
        ("gemini-extension.json", gemini),
        ("claude-directory/.claude-plugin/plugin.json", directory),
    ):
        if manifest.get("version") != claude["version"]:
            problems.append(
                f"{label}: version {manifest.get('version')} is not the plugin/ version {claude['version']}"
            )
        if manifest.get("name") != claude["name"]:
            problems.append(f"{label}: name {manifest.get('name')} is not {claude['name']}")
    server = load("plugin/.mcp.json")["mcpServers"]
    for label, got in (
        ("mcp_config.json", load("mcp_config.json").get("mcpServers")),
        ("gemini-extension.json", gemini.get("mcpServers")),
    ):
        if got != server:
            problems.append(f"{label}: mcpServers differs from plugin/.mcp.json")
    return problems


def unix(data):
    """Line endings as git stores them: a Windows checkout may hold CRLF."""
    return data.replace(b"\r\n", b"\n")


def main():
    check = sys.argv[1:] == ["--check"]
    if sys.argv[1:] and not check:
        sys.exit(__doc__)
    want = wanted()
    stale = [p for p, content in want.items() if not p.is_file() or unix(p.read_bytes()) != unix(content)]
    extra = sorted(existing() - set(want))

    def rel(p):
        return str(p.relative_to(ROOT))

    if check:
        problems = [f"out of date: {rel(p)}" for p in stale]
        problems += [f"not generated from plugin/, remove it: {rel(p)}" for p in extra]
        problems += manifest_problems()
        if problems:
            print("\n".join(problems), file=sys.stderr)
            print("\nRun scripts/gen-agent-plugins.py and commit the result.", file=sys.stderr)
            sys.exit(1)
        print(f"ok: {len(want)} generated files match plugin/, manifests agree")
        return

    for p in stale:
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_bytes(want[p])
        print(f"wrote {rel(p)}")
    for p in extra:
        p.unlink()
        print(f"removed {rel(p)}")
    if not stale and not extra:
        print("nothing to do")


if __name__ == "__main__":
    main()
